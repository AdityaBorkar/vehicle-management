import {
	integer,
	jsonb,
	pgTable,
	serial,
	text,
	timestamp,
	uniqueIndex,
} from "drizzle-orm/pg-core";

export const vehicles = pgTable(
	"vehicles",
	{
		bodyType: text("body_type"),
		color: text(),
		createdAt: timestamp("created_at", {
			mode: "date",
			withTimezone: true,
		}).defaultNow(),
		cubicCapacity: text("cubic_capacity"),
		emissionNorms: text("emission_norms"),
		fatherName: text("father_name"),
		financer: text(),
		fitnessNumber: text("fitness_number"),
		fitnessValidFrom: timestamp("fitness_valid_from", {
			mode: "date",
			withTimezone: true,
		}),
		fitnessValidTill: timestamp("fitness_valid_till", {
			mode: "date",
			withTimezone: true,
		}),
		fuelType: text("fuel_type"),
		fuelTypeRaw: text("fuel_type_raw"),
		grossVehicleWeightKg: text("gross_vehicle_weight_kg"),
		hypothecatedTo: text("hypothecated_to"),
		hypothecation: text(),
		id: serial().primaryKey(),
		insuranceCompany: text("insurance_company"),
		insurancePolicyNo: text("insurance_policy_no"),
		insuranceValidFrom: timestamp("insurance_valid_from", {
			mode: "date",
			withTimezone: true,
		}),
		insuranceValidTill: timestamp("insurance_valid_till", {
			mode: "date",
			withTimezone: true,
		}),
		make: text(),
		manufacturerModel: text("manufacturer_model"),
		manufacturingMonthYear: text("manufacturing_month_year"),
		mobileNumber: text("mobile_number"),
		model: text(),
		officeCode: text("office_code"),
		ownerName: text("owner_name"),
		ownershipSrNo: text("ownership_sr_no"),
		ownershipType: text("ownership_type"),
		permanentAddress: text("permanent_address"),
		permitNumber: text("permit_number"),
		permitType: text("permit_type"),
		permitValidFrom: timestamp("permit_valid_from", {
			mode: "date",
			withTimezone: true,
		}),
		permitValidTill: timestamp("permit_valid_till", {
			mode: "date",
			withTimezone: true,
		}),
		pollutionValidTill: timestamp("pollution_valid_till", {
			mode: "date",
			withTimezone: true,
		}),
		presentAddress: text("present_address"),
		pucNumber: text("puc_number"),
		rcFetchedAt: timestamp("rc_fetched_at", {
			mode: "date",
			withTimezone: true,
		}),
		rcProvider: text("rc_provider"),
		rcRaw: jsonb("rc_raw").$type<Record<string, unknown> | null>(),
		rcStatus: text("rc_status"),
		registrationAuthority: text("registration_authority"),
		registrationDate: timestamp("registration_date", {
			mode: "date",
			withTimezone: true,
		}),
		registrationNumber: text("registration_number").notNull(),
		rtoCode: text("rto_code"),
		rtoName: text("rto_name"),
		seatingCapacity: text("seating_capacity"),
		taxValidTill: timestamp("tax_valid_till", {
			mode: "date",
			withTimezone: true,
		}),
		unladenWeightKg: text("unladen_weight_kg"),
		updatedAt: timestamp("updated_at", {
			mode: "date",
			withTimezone: true,
		}).defaultNow(),
		userId: text("user_id").notNull(),
		vehicleClass: text("vehicle_class"),
		verificationId: text("verification_id"),
		vin: text(),
		wheelbase: text(),
		year: integer(),
	},
	(t) => [uniqueIndex("vehicles_reg_unique").on(t.registrationNumber)],
);
